/*******************************************************************************
PAW_Analysis — 光流传感器数据处理模块（业务层）
驱动层为 paw3395.c/h（软件 SPI 读写），本模块负责读取 + 通过共享内存传给 CM7_0
*******************************************************************************/


#include "zf_common_headfile.h"
#include "PAW3395_Analysis.h"


//-------------------------------------------------------------------------------------------------------------------
// 光流更新：读 paw3395 位移 + 写共享内存
// 供 CM7_1 周期调用（建议 20ms 一次，软 SPI 较慢）
//-------------------------------------------------------------------------------------------------------------------
void PAW_Analysis_Update(void)
{
    paw3395_get_motion();                       // 读 delta_x/y（驱动内部已累加）

    SHARED_FLOW_ADDR->flow_x_sum = paw3395_delta_x_i;
    SHARED_FLOW_ADDR->flow_y_sum = paw3395_delta_y_i;

    SHARED_FLOW_WRITE_SYNC();                   // 写回 cache，让 CM7_0 可见
}
